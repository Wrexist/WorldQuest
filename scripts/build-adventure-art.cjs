/** Package generated illustration masters; never synthesize teaching maps. */
const fs = require('node:fs');
const path = require('node:path');
const sharp = require('sharp');
(async () => {
  const source = path.resolve('docs/design/assets/adventure');
  const output = path.resolve('apps/mobile/assets/art/adventure');
  fs.mkdirSync(output, { recursive: true });
  const names = fs.readdirSync(source).filter(n => n.endsWith('.png')).map(n => n.slice(0, -4)).sort();
  for (const name of names) {
    await sharp(path.join(source, name + '.png')).resize({ width: name === 'island' ? 900 : 800, withoutEnlargement: true }).webp({ quality: 88, effort: 6 }).toFile(path.join(output, name + '.webp'));
  }
  fs.writeFileSync('apps/mobile/src/lib/adventure.generated.ts', '// Generated by scripts/build-adventure-art.cjs. Decorative illustrations only.\n' + names.map((n,i) => `import a${i} from '../../assets/art/${n === 'explorer' ? 'atlas-globe/welcome' : n === 'treasure' ? 'explorer-chest/closed' : `adventure/${n}`}.webp'`).join('\n') + '\nexport const ADVENTURE_ART = {\n' + names.map((n,i) => `  '${n}': a${i},`).join('\n') + '\n} as const\n');
  console.log('Packaged', names.length, 'adventure illustrations');
})().catch(e => { console.error(e); process.exitCode = 1; });
