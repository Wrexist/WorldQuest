/** Render lightweight map cards using the exact native globe geometry/shaders.
 * Natural Earth relief/borders, no invented or AI-generated geography.
 * One build-time GL context; no GL views or animation loops in scrolling cards.
 */
const fs = require('node:fs')
const path = require('node:path')
const http = require('node:http')
const { build } = require('esbuild')
const { chromium } = require('playwright')
const { launchOptions } = require('./chromium.cjs')
const root = path.resolve(__dirname, '..')
const out = path.join(root, 'apps/mobile/assets/geo/clay')
const atlas = 'apps/mobile/src/features/atlas'
const entry = `
import { GlobeRenderer } from './${atlas}/render/GlobeRenderer.ts';
import { atlasTheme } from './${atlas}/render/atlasTheme.ts';
import { colors } from './packages/design/src/tokens.ts';
import { ATLAS_COUNTRIES, ATLAS_REGION_FRAMES } from './${atlas}/data/atlas.generated.ts';
import { cameraForFrame, project, WORLD_CAMERA } from './${atlas}/geo/camera.ts';
import { parseAtlasGeometry, outlineSegments } from './${atlas}/geo/geometry.ts';
const viewport={width:640,height:480};
const canvas=document.createElement('canvas'); Object.assign(canvas,viewport); document.body.append(canvas);
const gl=canvas.getContext('webgl',{preserveDrawingBuffer:true,antialias:true,alpha:false});
if(!gl) throw Error('WebGL unavailable');
const renderer=new GlobeRenderer(gl,atlasTheme(colors,'light'),'high',true);
const load=async(src)=>{const im=new Image();im.src=src;await im.decode();return im};
const [surface,ids,bytes]=await Promise.all([load('/surface'),load('/ids'),fetch('/geometry').then(r=>r.arrayBuffer())]);
renderer.setSurface(surface);renderer.setCountryIds(ids,4096,2048);
const geometry=parseAtlasGeometry(bytes);
// Geographic overview for the entire continent, including continental North America.
const regions={...ATLAS_REGION_FRAMES,AN:{lat:-80,lon:0,radius:28}};
window.keys=[...Object.keys(ATLAS_COUNTRIES),...Object.keys(regions).map(r=>'region-'+r),'world'];
window.draw=(key)=>{
 const country=ATLAS_COUNTRIES[key],region=key.startsWith('region-')?key.slice(7):null;
 const frame=country?{...country.frame,radius:Math.max(5,country.frame.radius)}:regions[region];
 const camera=frame?cameraForFrame(frame,viewport,.74):{...WORLD_CAMERA,distance:4.4};
 const highlights=country?[[country.rasterId,'subject']]:[];
 renderer.setHighlights(new Map(highlights));
 const shape=country&&geometry.countries.get(country.id);
 renderer.setOutline(shape?outlineSegments(shape):null);
 renderer.render(camera,viewport);
 const output=document.createElement('canvas');Object.assign(output,viewport);
 const ctx=output.getContext('2d');ctx.drawImage(canvas,0,0);
 // Tiny islands/microstates retain a truthful locator at their verified anchor.
 if(country?.small){
  const p=project({lat:country.anchor[0],lon:country.anchor[1]},camera,viewport);
  if(p.visible){ctx.beginPath();ctx.arc(p.x,p.y,9,0,Math.PI*2);ctx.fillStyle='#FFD75B';ctx.fill();ctx.lineWidth=3;ctx.strokeStyle='#FFFFFF';ctx.stroke();}
 }
 return output.toDataURL('image/webp',.88).split(',')[1];
};
window.ready=true;
`
async function main() {
  const result = await build({ stdin: { contents: entry, resolveDir: root, loader: 'ts' }, bundle: true, write: false, format: 'esm', platform: 'browser', define: { __DEV__: 'false', 'process.env.EXPO_PUBLIC_ATLAS_LAB': '"1"' } })
  const resources = {
    '/surface': ['image/jpeg', fs.readFileSync(path.join(root, 'apps/mobile/assets/atlas/surface.bin'))],
    '/ids': ['image/png', fs.readFileSync(path.join(root, 'apps/mobile/assets/atlas/country-ids.bin'))],
    '/geometry': ['application/octet-stream', fs.readFileSync(path.join(root, 'apps/mobile/assets/atlas/countries.bin'))],
    '/app.js': ['text/javascript', result.outputFiles[0].contents],
    '/': ['text/html', '<html><body style="margin:0"><script type="module" src="/app.js"></script></body></html>'],
  }
  const server = http.createServer((req, res) => {
    const resource = resources[req.url]
    if (!resource) { res.writeHead(404); res.end(); return }
    res.setHeader('Content-Type', resource[0]); res.end(resource[1])
  })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  const browser = await chromium.launch(launchOptions({ args: ['--enable-unsafe-swiftshader'] }))
  try {
    const page = await browser.newPage()
    page.on('pageerror', error => console.error(error))
    await page.goto(`http://127.0.0.1:${server.address().port}`)
    await page.waitForFunction(() => window.ready)
    const keys = await page.evaluate(() => window.keys)
    fs.mkdirSync(out, { recursive: true })
    for (const key of keys) {
      const data = await page.evaluate(key => window.draw(key), key)
      fs.writeFileSync(path.join(out, key + '.webp'), Buffer.from(data, 'base64'))
    }
    const manifest = '// Generated by node scripts/build-clay-maps.cjs. Natural Earth + shared GlobeRenderer.\n'
      + keys.map((k,i) => `import m${i} from '../../assets/geo/clay/${k}.webp'`).join('\n')
      + '\nexport const CLAY_MAPS: Readonly<Record<string, number | string>> = {\n'
      + keys.map((k,i) => `  '${k}': m${i},`).join('\n') + '\n}\n'
    fs.writeFileSync(path.join(root, 'apps/mobile/src/lib/clay-maps.generated.ts'), manifest)
    console.log(`${keys.length} shared-renderer clay map previews (${(keys.reduce((n,k)=>n+fs.statSync(path.join(out,k+'.webp')).size,0)/1024/1024).toFixed(2)} MiB).`)
  } finally { await browser.close(); server.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
