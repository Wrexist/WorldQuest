// Resize complete transparent artwork; never slice, crop or composite character parts.
// The derived frames are whole poses too: the same pose with a new face made from his
// own clay parts (scripts/lib/clay-face.cjs), identical to it everywhere but the face.
const fs = require('node:fs')
const path = require('node:path')
const sharp = require('sharp')
const { express, partsFrom } = require('./lib/clay-face.cjs')
const root = path.resolve(__dirname, '..')
/** The four generated poses. Resting lends its closed eyes and smile to every new face. */
const masters = ['welcome', 'celebrate', 'thinking', 'resting']
/** New faces on those poses. A blink frame is laid over its pose; the rest are poses of their own. */
const faces = {
  'welcome-blink': { from: 'welcome', eyes: 'blink' },
  'celebrate-blink': { from: 'celebrate', eyes: 'blink' },
  'thinking-blink': { from: 'thinking', eyes: 'blink' },
  laughing: { from: 'celebrate', eyes: 'happy' },
  proud: { from: 'celebrate', eyes: 'happy', mouth: 'smile' },
  wink: { from: 'welcome', eyes: 'wink' },
}
const moods = { welcome: 'welcome', celebrate: 'celebrate', thinking: 'thinking', resting: 'resting', encouraging: 'welcome', laughing: 'laughing', surprised: 'celebrate', proud: 'proud', sleepy: 'resting', wink: 'wink' }
// Laughing, proud and resting have their eyes shut already; a wink is a blink of its own.
const blinks = { welcome: 'welcome-blink', celebrate: 'celebrate-blink', thinking: 'thinking-blink' }
const name = file => file.replace(/-(\w)/g, (_, c) => c.toUpperCase())
async function main() {
  const out = path.join(root, 'apps/mobile/assets/art/atlas-clay')
  fs.mkdirSync(out, { recursive: true })
  for (const pose of masters) {
    const input = path.join(root, 'docs/design/assets/atlas-liquid-clay', `${pose}.png`)
    const metadata = await sharp(input).metadata()
    if (!metadata.hasAlpha || metadata.width !== metadata.height) throw new Error(`${pose}: expected square transparent artwork`)
    await sharp(input).resize(512, 512, { fit: 'contain' }).png({ compressionLevel: 9 }).toFile(path.join(out, `${pose}.png`))
    console.log(`${pose}: 512 x 512 RGBA, ${Math.round(fs.statSync(path.join(out, `${pose}.png`)).size / 1024)} KiB`)
  }
  const parts = await partsFrom(path.join(out, 'resting.png'))
  for (const [face, recipe] of Object.entries(faces)) {
    fs.writeFileSync(path.join(out, `${face}.png`), await express(path.join(out, `${recipe.from}.png`), parts, recipe, face))
    console.log(`${face}: ${recipe.from} with ${recipe.eyes} eyes${recipe.mouth ? ` and a ${recipe.mouth}` : ''}, ${Math.round(fs.statSync(path.join(out, `${face}.png`)).size / 1024)} KiB`)
  }
  const used = new Set([...Object.values(moods), ...Object.values(blinks)])
  fs.writeFileSync(path.join(root, 'apps/mobile/src/lib/atlasClay.generated.ts'), [
    '// Generated by scripts/build-clay-mascot.cjs. Complete transparent poses, no sprite sheets.',
    ...[...masters, ...Object.keys(faces)].filter(file => used.has(file)).map(file => `import ${name(file)} from '../../assets/art/atlas-clay/${file}.png'`),
    '', 'export const ATLAS_CLAY = {',
    ...Object.entries(moods).map(([mood, art]) => `  ${mood}: ${name(art)},`),
    '} as const', '', 'export type AtlasClayMood = keyof typeof ATLAS_CLAY', '',
    '/** The same complete pose with its eyes closed, for a blink. Only open-eyed poses have one. */',
    'export const ATLAS_CLAY_BLINK: { readonly [mood in AtlasClayMood]?: typeof welcome } = {',
    ...Object.entries(moods).filter(([, art]) => art in blinks).map(([mood, art]) => `  ${mood}: ${name(blinks[art])},`),
    '}', '',
  ].join('\n'))
}
main().catch(error => { console.error(error); process.exitCode = 1 })
