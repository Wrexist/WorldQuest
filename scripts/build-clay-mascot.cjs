// Resize complete transparent artwork; never slice, crop or composite character parts.
const fs = require('node:fs')
const path = require('node:path')
const sharp = require('sharp')
const root = path.resolve(__dirname, '..')
const moods = { welcome: 'welcome', celebrate: 'celebrate', thinking: 'thinking', resting: 'resting', encouraging: 'welcome', laughing: 'celebrate', surprised: 'celebrate', proud: 'welcome', sleepy: 'resting', wink: 'welcome' }
async function main() {
  const out = path.join(root, 'apps/mobile/assets/art/atlas-clay')
  fs.mkdirSync(out, { recursive: true })
  for (const name of new Set(Object.values(moods))) {
    const input = path.join(root, 'docs/design/assets/atlas-liquid-clay', `${name}.png`)
    const metadata = await sharp(input).metadata()
    if (!metadata.hasAlpha || metadata.width !== metadata.height) throw new Error(`${name}: expected square transparent artwork`)
    await sharp(input).resize(512, 512, { fit: 'contain' }).png({ compressionLevel: 9 }).toFile(path.join(out, `${name}.png`))
    console.log(`${name}: 512 x 512 RGBA, ${Math.round(fs.statSync(path.join(out, `${name}.png`)).size / 1024)} KiB`)
  }
  fs.writeFileSync(path.join(root, 'apps/mobile/src/lib/atlasClay.generated.ts'), [
    '// Generated by scripts/build-clay-mascot.cjs. Complete transparent poses, no sprite sheets.',
    ...[...new Set(Object.values(moods))].map(name => `import ${name} from '../../assets/art/atlas-clay/${name}.png'`),
    '', 'export const ATLAS_CLAY = {',
    ...Object.entries(moods).map(([mood, art]) => `  ${mood}: ${art},`),
    '} as const', '', 'export type AtlasClayMood = keyof typeof ATLAS_CLAY', '',
  ].join('\n'))
}
main().catch(error => { console.error(error); process.exitCode = 1 })
