/** Derive compressed UI assets and alpha bounds from the versioned daylight masters. */
const { chromium } = require('playwright')
const { launchOptions } = require('./chromium.cjs')
const fs = require('node:fs')
const path = require('node:path')

async function main() {
  const root = path.resolve(__dirname, '..')
  const source = path.join(root, 'docs/design/assets/daylight')
  const target = path.join(root, 'apps/mobile/assets/art/daylight')
  fs.mkdirSync(target, { recursive: true })
  const browser = await chromium.launch(launchOptions())
  const page = await browser.newPage()
  const names = fs.readdirSync(source).filter(f => f.endsWith('.png')).map(f => f.slice(0, -4))
  const records = {}
  try {
    for (const name of names) {
      const data = fs.readFileSync(path.join(source, `${name}.png`)).toString('base64')
      const result = await page.evaluate(async (data) => {
        const img = new Image(); img.src = `data:image/png;base64,${data}`; await img.decode()
        const canvas = document.createElement('canvas')
        canvas.width = 640; canvas.height = Math.round(640 * img.height / img.width)
        const ctx = canvas.getContext('2d'); ctx.drawImage(img, 0, 0, canvas.width, canvas.height)
        const pixels = ctx.getImageData(0, 0, canvas.width, canvas.height).data
        let x0=canvas.width, y0=canvas.height, x1=0, y1=0
        for(let y=0;y<canvas.height;y++) for(let x=0;x<canvas.width;x++) {
          if(pixels[(y*canvas.width+x)*4+3] > 8) {
            x0=Math.min(x0,x); y0=Math.min(y0,y); x1=Math.max(x1,x); y1=Math.max(y1,y)
          }
        }
        return { data:canvas.toDataURL('image/webp', .82).split(',')[1], geometry: {
          x:x0/canvas.width,y:y0/canvas.height,w:(x1-x0+1)/canvas.width,h:(y1-y0+1)/canvas.height,
          aspect:canvas.width/canvas.height,
        }}
      }, data)
      const bytes = Buffer.from(result.data, 'base64')
      if (bytes.length > 120*1024) throw new Error(`${name} exceeds the 120KB UI budget`)
      fs.writeFileSync(path.join(target, `${name}.webp`), bytes)
      records[name]=result.geometry
      console.log(`${name}: ${Math.round(bytes.length/1024)}KB`)
    }
  } finally { await browser.close() }
  // DaylightIllustration resolves these names to the newer expedition/studio/chest art.
  const superseded = ['heart', 'passport', 'gem', 'star-trophy', 'treasure-chest', 'chest-base', 'chest-lid']
  const runtimeNames = names.filter(name => !superseded.includes(name))
  const imports = runtimeNames.map((name,i)=>`import art${i} from '../../assets/art/daylight/${name}.webp'`).join('\n')
  const entries = runtimeNames.map((name,i)=>`  '${name}': { asset: art${i}, geometry: ${JSON.stringify(records[name])} },`).join('\n')
  fs.writeFileSync(path.join(root,'apps/mobile/src/lib/daylight.generated.ts'),
    `// Generated by node scripts/build-daylight-art.cjs. Preserve masters and alpha.\n${imports}\n\nexport const DAYLIGHT_ART = {\n${entries}\n} as const\n`)
}
main().catch(e=>{console.error(e);process.exitCode=1})
