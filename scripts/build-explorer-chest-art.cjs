/** Package UI derivatives from the editable explorer chest's exact Blender renders. */
const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const sharp = require('sharp')

const ROOT = path.resolve(__dirname, '..')
const SOURCE = path.join(ROOT, 'docs/design/assets/explorer-chest')
const TARGET = path.join(ROOT, 'apps/mobile/assets/art/explorer-chest')
const digest = bytes => crypto.createHash('sha256').update(bytes).digest('hex')
const assert = (condition, message) => { if (!condition) throw new Error(message) }

async function bounds(file, expectedSize) {
  const { data, info } = await sharp(file).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
  assert(info.width === expectedSize && info.height === expectedSize, `${file}: unexpected dimensions`)
  let x0 = info.width, y0 = info.height, x1 = 0, y1 = 0, pixels = 0
  for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) {
    if (data[(y * info.width + x) * 4 + 3] > 8) {
      x0 = Math.min(x0, x); x1 = Math.max(x1, x)
      y0 = Math.min(y0, y); y1 = Math.max(y1, y); pixels++
    }
  }
  assert(pixels > expectedSize * expectedSize * .15, `${file}: empty or tiny silhouette`)
  assert(x0 > 1 && y0 > 1 && x1 < info.width - 2 && y1 < info.height - 2, `${file}: clipped silhouette`)
  return { x: x0 / info.width, y: y0 / info.height, w: (x1 - x0 + 1) / info.width, h: (y1 - y0 + 1) / info.height, aspect: 1 }
}

async function main() {
  fs.mkdirSync(TARGET, { recursive: true })
  const geometry = {}, outputs = [], frames = []
  for (const name of ['closed', 'opened']) {
    const source = path.join(SOURCE, `${name}.png`)
    geometry[name] = await bounds(source, 640)
    const bytes = await sharp(source).webp({ quality: 88, alphaQuality: 100, effort: 6 }).toBuffer()
    assert(bytes.length < 120 * 1024, `${name}: exceeds 120KB budget`)
    fs.writeFileSync(path.join(TARGET, `${name}.webp`), bytes)
    outputs.push({ file: `${name}.webp`, bytes: bytes.length, sha256: digest(bytes), geometry: geometry[name] })
  }
  for (let i = 0; i < 40; i++) {
    const file = path.join(SOURCE, 'frames', `${String(i).padStart(2, '0')}.png`)
    frames.push({ index: i, sha256: digest(fs.readFileSync(file)), geometry: await bounds(file, 480) })
  }
  const sheet = await sharp({ create: { width: 3840, height: 2400, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
    .composite(frames.map(({ index }) => ({ input: path.join(SOURCE, 'frames', `${String(index).padStart(2, '0')}.png`), left: (index % 8) * 480, top: Math.floor(index / 8) * 480 })))
    .webp({ quality: 92, alphaQuality: 100, effort: 6 }).toBuffer()
  assert(sheet.length < 1600 * 1024, 'Film exceeds 1600KB runtime budget')
  assert(new Set(frames.map(f => f.sha256)).size >= 25, 'Film is missing motion')
  fs.writeFileSync(path.join(TARGET, 'chest-sheet.webp'), sheet)
  outputs.push({ file: 'chest-sheet.webp', bytes: sheet.length, sha256: digest(sheet), width: 3840, height: 2400, frames: 40 })
  const glb = fs.readFileSync(path.join(SOURCE, 'explorer-chest.glb'))
  assert(glb.toString('ascii', 0, 4) === 'glTF' && glb.readUInt32LE(4) === 2, 'Invalid glTF header')
  assert(glb.length === glb.readUInt32LE(8), 'GLB declared length does not match bytes')
  const json = JSON.parse(glb.toString('utf8', 20, 20 + glb.readUInt32LE(12)).trim())
  const triangles = json.meshes.reduce((sum, mesh) => sum + mesh.primitives.reduce((n, primitive) => n + json.accessors[primitive.indices].count / 3, 0), 0)
  assert(triangles < 100000 && glb.length < 5 * 1024 * 1024, 'GLB exceeds topology/file budget')
  assert(json.animations?.length > 0, 'GLB is missing its opening animation')
  assert(json.images?.every(img => img.bufferView !== undefined), 'GLB textures must be embedded')
  const declaration = `// Generated by node scripts/build-explorer-chest-art.cjs. Preserve masters, alpha and frame alignment.\n` +
    `import closed from '../../assets/art/explorer-chest/closed.webp'\n` +
    `import opened from '../../assets/art/explorer-chest/opened.webp'\n` +
    `import sheet from '../../assets/art/explorer-chest/chest-sheet.webp'\n\n` +
    `export const EXPLORER_CHEST = { closed, opened, sheet } as const\n` +
    `export const EXPLORER_CHEST_SEQUENCE = { frames: 40, columns: 8, rows: 5, fps: 20, frameSize: 480 } as const\n` +
    `export const EXPLORER_CHEST_GEOMETRY = ${JSON.stringify(geometry, null, 2)} as const\n`
  fs.writeFileSync(path.join(ROOT, 'apps/mobile/src/lib/explorerChest.generated.ts'), declaration)
  const validation = {
    created: '2026-10-02', outputs, frameBounds: frames,
    model: { bytes: glb.length, triangles, meshes: json.meshes.length, materials: json.materials.length, animations: json.animations.map(a => ({ name: a.name, channels: a.channels.length })), embeddedImages: json.images.length },
    checks: { transparentPaddingAllFrames: true, runtimeBudgets: true, modelBudget: true, animationPresent: true, textureEmbedded: true },
    evidenceBoundary: 'Blender rendered masters and film; binary glTF inspection and static packaging checks. UI runtime/import verification is recorded separately.',
  }
  fs.writeFileSync(path.join(SOURCE, 'validation.json'), JSON.stringify(validation, null, 2) + '\n')
  console.log(JSON.stringify({ outputs, model: validation.model }, null, 2))
}
main().catch(error => { console.error(error); process.exitCode = 1 })
