/**
 * Pack Atlas's rendered animation frames into one sprite sheet per mood, plus a still.
 *
 * Input:  node_modules/.cache/globe-mascot/<mood>/NNN.png   (scripts/build-globe-mascot.py --sheets)
 *         docs/design/assets/world-mascot-3d/stills/<mood>.png (--stills)
 * Output: apps/mobile/assets/art/atlas-globe/<mood>-sheet.webp, <mood>.webp
 *         apps/mobile/src/lib/atlasGlobe.generated.ts
 *
 * The same playback contract as the treasure chest (TreasureChest.tsx): a grid of equal
 * cells, stepped through by translating one image, so the app needs no 3D engine and no
 * video decoder — the frames are real Blender renders, the runtime only slides a picture.
 *
 * Run: node scripts/build-globe-mascot-art.cjs
 */
const fs = require('node:fs')
const path = require('node:path')
const sharp = require('sharp')
const { featherImage } = require('./lib/feather-alpha.cjs')

const ROOT = path.resolve(__dirname, '..')
const FRAMES = path.join(ROOT, 'node_modules/.cache/globe-mascot')
const STILLS = path.join(ROOT, 'docs/design/assets/world-mascot-3d/stills')
const OUT = path.join(ROOT, 'apps/mobile/assets/art/atlas-globe')
const TS = path.join(ROOT, 'apps/mobile/src/lib/atlasGlobe.generated.ts')
const MOODS = ['welcome', 'celebrate', 'thinking', 'resting', 'encouraging', 'laughing', 'surprised', 'proud', 'sleepy', 'wink']
const COUNT = 36, COLUMNS = 6, ROWS = 6, CELL = 320, FPS = 18, STILL = 640
/** Per sheet. A mood is on screen alone, so this is what one appearance costs to decode. */
const SHEET_BUDGET_KB = 640

async function main() {
  fs.mkdirSync(OUT, { recursive: true })
  const lines = []
  let total = 0
  for (const mood of MOODS) {
    const dir = path.join(FRAMES, mood)
    const files = Array.from({ length: COUNT }, (_, i) => path.join(dir, `${String(i).padStart(3, '0')}.png`))
    const missing = files.filter((f) => !fs.existsSync(f))
    if (missing.length > 0) throw new Error(`${mood}: ${missing.length} frame(s) not rendered — run build-globe-mascot.py --sheets`)
    const cells = await Promise.all(files.map(async (f) => featherImage(await sharp(f).resize(CELL, CELL).png().toBuffer())))
    const grid = await sharp({ create: { width: CELL * COLUMNS, height: CELL * ROWS, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
      .composite(cells.map((input, i) => ({ input, left: (i % COLUMNS) * CELL, top: Math.floor(i / COLUMNS) * CELL })))
      .png()
      .toBuffer()
    // Busy moods (sparkles, big arm swings) compress worse; step quality down rather
    // than raise the budget, and stop at a floor below which the land edges smear.
    let sheet
    for (let quality = 82; quality >= 58; quality -= 3) {
      sheet = await sharp(grid).webp({ quality, alphaQuality: 90, effort: 6 }).toBuffer()
      if (sheet.length <= SHEET_BUDGET_KB * 1024) break
    }
    if (sheet.length > SHEET_BUDGET_KB * 1024) throw new Error(`${mood}: sheet is ${Math.round(sheet.length / 1024)} KB, over ${SHEET_BUDGET_KB} KB`)
    fs.writeFileSync(path.join(OUT, `${mood}-sheet.webp`), sheet)
    const still = await sharp(await featherImage(await sharp(path.join(STILLS, `${mood}.png`)).resize(STILL, STILL).png().toBuffer())).webp({ quality: 88, alphaQuality: 95, effort: 6 }).toBuffer()
    fs.writeFileSync(path.join(OUT, `${mood}.webp`), still)
    total += sheet.length + still.length
    lines.push(mood)
    console.log(`  ${mood.padEnd(12)} sheet ${Math.round(sheet.length / 1024)} KB · still ${Math.round(still.length / 1024)} KB`)
  }
  const imports = lines.flatMap((m, i) => [
    `import sheet${i} from '../../assets/art/atlas-globe/${m}-sheet.webp'`,
    `import still${i} from '../../assets/art/atlas-globe/${m}.webp'`,
  ])
  const entries = lines.map((m, i) => `  '${m}': { sheet: sheet${i}, still: still${i} },`)
  fs.writeFileSync(TS, [
    '// Generated by scripts/build-globe-mascot-art.cjs from Blender renders (scripts/build-globe-mascot.py). Do not edit.',
    ...imports,
    '',
    `export const ATLAS_SEQUENCE = { frames: ${COUNT}, columns: ${COLUMNS}, rows: ${ROWS}, fps: ${FPS} } as const`,
    '',
    'export const ATLAS_GLOBE = {',
    ...entries,
    '} as const',
    '',
    'export type AtlasGlobeMood = keyof typeof ATLAS_GLOBE',
    '',
  ].join('\n'))
  console.log(`✓ ${lines.length} moods · ${Math.round(total / 1024)} KB total → ${path.relative(ROOT, OUT)}`)
}

main().catch((error) => { console.error(`✗ ${error.message}`); process.exit(1) })
