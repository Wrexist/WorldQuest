/** Package the original 3D chest and selectively restore the golden expedition art. */
const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const { chromium } = require('playwright')
const { launchOptions } = require('./chromium.cjs')
const root = path.resolve(__dirname, '..')
const output = path.join(root, 'apps/mobile/assets/art/soft')
const names = ['atlas/explorer','atlas/welcome','atlas/celebrate','atlas/encouraging','atlas/resting','atlas/thinking','atlas/waving-back','atlas/broken-compass','rewards/globe','states/hearts-empty']
async function main() {
  fs.mkdirSync(output, { recursive: true })
  const browser = await chromium.launch(launchOptions())
  try {
    const page = await browser.newPage()
    const records = {}
    const studioNames = { heart: 'heart', 'star-trophy': 'star', coins: 'coins' }
    for (const file of Object.values(studioNames)) fs.copyFileSync(path.join(root,'docs/design/3d/rewards/icons',file+'.webp'), path.join(output,'studio-'+file+'.webp'))
    for (const name of [...names, ...Object.values(studioNames).map(n => 'soft/studio-'+n)]) {
      const bytes = fs.readFileSync(path.join(root, 'apps/mobile/assets/art', name + '.webp'))
      records[name] = await page.evaluate(async data => {
        const i = new Image(); i.src = 'data:image/webp;base64,' + data; await i.decode()
        const c = document.createElement('canvas'); c.width = i.width; c.height = i.height
        const x = c.getContext('2d'); x.drawImage(i, 0, 0)
        const pixels = x.getImageData(0, 0, c.width, c.height).data
        let left=c.width, top=c.height, right=0, bottom=0
        for(let y=0;y<c.height;y++) for(let x=0;x<c.width;x++) if(pixels[(y*c.width+x)*4+3]>12) {
          left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y)
        }
        return {aspect:c.width/c.height,x:left/c.width,y:top/c.height,w:(right-left+1)/c.width,h:(bottom-top+1)/c.height}
      }, bytes.toString('base64'))
    }
    fs.writeFileSync(path.join(root,'apps/mobile/src/lib/classic.generated.ts'), `// Generated by build-soft-assets.cjs. Original retained expedition assets.\n${names.map((n,i)=>`import a${i} from '../../assets/art/${n}.webp'`).join('\n')}\nexport const CLASSIC_ART = {\n${names.map((n,i)=>`  '${n}': { asset: a${i}, geometry: ${JSON.stringify(records[n])} },`).join('\n')}\n} as const\n`)
    const studioEntries=Object.entries(studioNames)
    fs.writeFileSync(path.join(root,'apps/mobile/src/lib/studio.generated.ts'),`// Generated from the user-supplied 3D Asset Studio renders.\n${studioEntries.map(([name,file],i)=>`import a${i} from '../../assets/art/soft/studio-${file}.webp'`).join('\n')}\nexport const STUDIO_ART = {\n${studioEntries.map(([name,file],i)=>`  '${name}': { asset:a${i}, geometry:${JSON.stringify(records['soft/studio-'+file])} },`).join('\n')}\n} as const\n`)
    const frames = Array.from({length:40},(_,i)=>fs.readFileSync(path.join(root,'docs/design/3d/chest/frames',`${String(i).padStart(3,'0')}.webp`)).toString('base64'))
    const packaged = await page.evaluate(async frames => {
      const images = await Promise.all(frames.map(async data=>{const i=new Image();i.src='data:image/webp;base64,'+data;await i.decode();return i}))
      const c=document.createElement('canvas');c.width=320*8;c.height=320*5
      const ctx=c.getContext('2d');images.forEach((im,i)=>ctx.drawImage(im,(i%8)*320,Math.floor(i/8)*320,320,320))
      const sheet=c.toDataURL('image/webp',1).split(',')[1]
      c.width=c.height=320;ctx.drawImage(images[0],0,0,320,320)
      const closed=c.toDataURL('image/webp',1).split(',')[1]
      ctx.clearRect(0,0,320,320);ctx.drawImage(images[39],0,0,320,320)
      return {sheet,closed,opened:c.toDataURL('image/webp',1).split(',')[1]}
    },frames)
    const gem = fs.readFileSync(path.join(root,'docs/design/assets/chest-v2/gem.png')).toString('base64')
    packaged.gem = await page.evaluate(async data => { const i=new Image();i.src='data:image/png;base64,'+data;await i.decode();const c=document.createElement('canvas');c.width=c.height=256;c.getContext('2d').drawImage(i,0,0,256,256);return c.toDataURL('image/webp',.9).split(',')[1] },gem)
    const files={}
    for(const [name,data] of Object.entries(packaged)) {
      const bytes=Buffer.from(data,'base64');const file=`chest-${name}.webp`
      fs.writeFileSync(path.join(output,file),bytes)
      files[file]={bytes:bytes.length,sha256:crypto.createHash('sha256').update(bytes).digest('hex')}
    }
    const geometry = {}
    for (const name of ['closed','gem']) geometry[name] = await page.evaluate(async data => {
      const i=new Image();i.src='data:image/webp;base64,'+data;await i.decode();
      const c=document.createElement('canvas');c.width=i.width;c.height=i.height;const x=c.getContext('2d');x.drawImage(i,0,0);
      const p=x.getImageData(0,0,c.width,c.height).data;let l=c.width,t=c.height,r=0,b=0;
      for(let y=0;y<c.height;y++)for(let x=0;x<c.width;x++)if(p[(y*c.width+x)*4+3]>12){l=Math.min(l,x);r=Math.max(r,x);t=Math.min(t,y);b=Math.max(b,y)}
      return {aspect:c.width/c.height,x:l/c.width,y:t/c.height,w:(r-l+1)/c.width,h:(b-t+1)/c.height};
    }, packaged[name])
    fs.writeFileSync(path.join(root,'apps/mobile/src/lib/soft.generated.ts'),`// Generated by build-soft-assets.cjs from inspected 3D renders.\nimport chest from '../../assets/art/soft/chest-closed.webp'\nimport gem from '../../assets/art/soft/chest-gem.webp'\nexport const CHEST_SEQUENCE = { frames: 40, fps: 20, columns: 8, rows: 5 } as const\nexport const SOFT_ART = {\n  'treasure-chest': { asset: chest, geometry: ${JSON.stringify(geometry.closed)} },\n  gem: { asset: gem, geometry: ${JSON.stringify(geometry.gem)} },\n} as const\n`)
    for (const file of Object.values(studioNames)) {
      const name='studio-'+file+'.webp';const bytes=fs.readFileSync(path.join(output,name));
      files[name]={bytes:bytes.length,sha256:crypto.createHash('sha256').update(bytes).digest('hex')}
    }
    fs.writeFileSync(path.join(root,'docs/design/assets/chest-v2/validation.json'),JSON.stringify({source:'scripts/build-chest-v2.py + docs/design/3d/chest.scene.js (3d-asset-studio)',author:'WorldQuest original procedural geometry',license:'Project-owned original artwork; no external meshes or textures',frames:40,fps:20,sheet:{width:2560,height:1600,columns:8,frameSize:320},files},null,2)+'\n')
    console.log('Soft assets packaged', files)
  } finally { await browser.close() }
}
main().catch(e=>{console.error(e);process.exitCode=1})
